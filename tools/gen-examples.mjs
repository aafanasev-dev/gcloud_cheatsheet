#!/usr/bin/env node
// Builds js/data/examples.js from examples/<app>/meta.mjs plus the source files
// each meta lists, so the code shown on the site is exactly the code in the
// repo. Run after editing anything under examples/:  node tools/gen-examples.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const APPS = ['bookstore', 'petshop', 'imagestore'];

const subtopics = [];
for (const app of APPS) {
  const dir = path.join(root, 'examples', app);
  const { default: meta } = await import(pathToFileURL(path.join(dir, 'meta.mjs')));
  const { files, ...rest } = meta;
  const source = {
    title: 'Source code',
    note: `Full source in the repository under \`examples/${app}/\`.`,
    files: files.map(f => ({
      name: f.path,
      lang: f.lang,
      open: !!f.open,
      code: fs.readFileSync(path.join(dir, f.path), 'utf8').replace(/\s+$/, ''),
    })),
    cmds: [],
  };
  subtopics.push({ ...rest, sections: [source, ...meta.sections] });
}

const topic = {
  id: 'examples',
  title: 'Examples',
  icon: 'layers',
  color: 'ex',
  description: 'Three complete applications with their full source code and every gcloud command needed to build, secure, deploy, test and remove them. Together they touch every topic on this site.',
  useCases: [
    'Starting points to copy for your own projects',
    'Seeing how storage, compute, IAM, data exchange, APIs and Gemini fit together',
    'Runbooks: each page goes from an empty project to a working app and back to clean',
  ],
  subtopics,
};

const out = path.join(root, 'js', 'data', 'examples.js');
fs.writeFileSync(out, `// GENERATED by tools/gen-examples.mjs from examples/**. Do not edit by hand.\nexport default ${JSON.stringify(topic, null, 1)};\n`);
console.log(`wrote ${path.relative(root, out)}: ${subtopics.length} apps, ${subtopics.reduce((n, s) => n + s.sections[0].files.length, 0)} files`);
